export type GetStartedStepId =
  | "account"
  | "username"
  | "photo"
  | "connection"
  | "workspace";

export type GetStartedStep = {
  id: GetStartedStepId;
  title: string;
  description: string;
  complete: boolean;
};

export type GetStartedProgressInput = {
  hasAccount: boolean;
  username: string | null | undefined;
  usernameAutoGenerated: boolean | undefined;
  image: string | null | undefined;
  acceptedConnectionCount: number;
  outgoingConnectionRequestCount: number;
  workspaceCount: number;
};

export type GetStartedProgress = {
  steps: GetStartedStep[];
  completedCount: number;
  totalCount: number;
  remainingCount: number;
  percent: number;
  isComplete: boolean;
  nextStep: GetStartedStep | null;
};

export const GET_STARTED_WINDOW_DAYS = 14;

export function isGetStartedWindowExpired(
  createdAt: string | Date | null | undefined,
  now: Date = new Date(),
): boolean {
  if (!createdAt) return false;
  const createdAtMs = new Date(createdAt).getTime();
  if (!Number.isFinite(createdAtMs)) return false;
  return now.getTime() - createdAtMs >= GET_STARTED_WINDOW_DAYS * 86_400_000;
}

export function getStartedHeadline(remainingCount: number): string {
  if (remainingCount <= 0) return "You’re all set!";
  if (remainingCount === 1) return "You’re almost there!";
  if (remainingCount === 2) return "You’re making great progress!";
  if (remainingCount <= 4) return "You’re off to a great start!";
  return "Let’s get you started";
}

export function buildGetStartedProgress(
  input: GetStartedProgressInput,
): GetStartedProgress {
  const steps: GetStartedStep[] = [
    {
      id: "account",
      title: "Create your account",
      description: "Your Alenio account is ready.",
      complete: input.hasAccount,
    },
    {
      id: "username",
      title: "Choose your username",
      description: "Make it easy for people to find you.",
      complete: Boolean(input.username?.trim()),
    },
    {
      id: "photo",
      title: "Add a profile photo",
      description: "Help people recognize you.",
      complete: Boolean(input.image?.trim()),
    },
    {
      id: "connection",
      title: "Send your first connection request",
      description: "Find someone you know on Alenio.",
      complete:
        input.acceptedConnectionCount > 0 ||
        input.outgoingConnectionRequestCount > 0,
    },
    {
      id: "workspace",
      title: "Join or create a workspace",
      description: "Collaborate and get more done.",
      complete: input.workspaceCount > 0,
    },
  ];
  const completedCount = steps.filter((step) => step.complete).length;
  const totalCount = steps.length;
  const remainingCount = totalCount - completedCount;

  return {
    steps,
    completedCount,
    totalCount,
    remainingCount,
    percent: Math.round((completedCount / totalCount) * 100),
    isComplete: remainingCount === 0,
    nextStep: steps.find((step) => !step.complete) ?? null,
  };
}
