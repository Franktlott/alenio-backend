import { useEffect, useRef } from "react";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { api } from "@/lib/api/api";
import { fetchMeUser, ME_QUERY_KEY, type MeUser } from "@/lib/auth/me-query";
import {
  buildGetStartedProgress,
  isGetStartedWindowExpired,
  type GetStartedProgress,
} from "@/lib/get-started-progress";
import type { ConnectionsResponse, Team } from "@/lib/types";

export type GetStartedProgressState = GetStartedProgress & {
  isResolved: boolean;
  hasCompletedOnce: boolean;
  isExpired: boolean;
};

export function useGetStartedProgress(): GetStartedProgressState {
  const queryClient = useQueryClient();
  const completionWriteUserId = useRef<string | null>(null);
  const meQuery = useQuery<MeUser | null>({
    queryKey: ME_QUERY_KEY,
    queryFn: () => fetchMeUser(),
  });
  const teamsQuery = useQuery<Team[]>({
    queryKey: ["teams"],
    queryFn: () => api.get<Team[]>("/api/teams"),
  });
  const connectionsQuery = useQuery<ConnectionsResponse>({
    queryKey: ["connections", meQuery.data?.id ?? "anonymous"],
    queryFn: () => api.get<ConnectionsResponse>("/api/connections"),
    enabled: Boolean(meQuery.data?.id),
    staleTime: 0,
  });

  const progress = buildGetStartedProgress({
    hasAccount: Boolean(meQuery.data?.id),
    username: meQuery.data?.username,
    usernameAutoGenerated: meQuery.data?.usernameAutoGenerated,
    image: meQuery.data?.image,
    acceptedConnectionCount: connectionsQuery.data?.accepted.length ?? 0,
    outgoingConnectionRequestCount: connectionsQuery.data?.outgoing.length ?? 0,
    workspaceCount: teamsQuery.data?.length ?? 0,
  });
  const userId = meQuery.data?.id ?? null;
  const isExpired = isGetStartedWindowExpired(meQuery.data?.createdAt);
  const liveProgressResolved =
    !meQuery.isLoading &&
    !teamsQuery.isLoading &&
    !connectionsQuery.isLoading &&
    !meQuery.isError &&
    !teamsQuery.isError &&
    !connectionsQuery.isError;
  useEffect(() => {
    if (
      !userId ||
      !liveProgressResolved ||
      !progress.isComplete ||
      meQuery.data?.getStartedCompletedAt ||
      completionWriteUserId.current === userId
    ) {
      return;
    }

    completionWriteUserId.current = userId;
    void api
      .post<{ getStartedCompletedAt: string }>(
        "/api/me/get-started-completion",
        {},
      )
      .then(({ getStartedCompletedAt }) => {
        queryClient.setQueryData<MeUser | null>(ME_QUERY_KEY, (current) =>
          current ? { ...current, getStartedCompletedAt } : current,
        );
      })
      .catch(() => {
        completionWriteUserId.current = null;
      });
  }, [
    liveProgressResolved,
    meQuery.data?.getStartedCompletedAt,
    progress.isComplete,
    queryClient,
    userId,
  ]);

  return {
    ...progress,
    isResolved: liveProgressResolved,
    hasCompletedOnce:
      progress.isComplete || Boolean(meQuery.data?.getStartedCompletedAt),
    isExpired,
  };
}
