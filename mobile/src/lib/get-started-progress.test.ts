import { describe, expect, test } from "bun:test";
import {
  buildGetStartedProgress,
  getStartedHeadline,
  isGetStartedWindowExpired,
} from "./get-started-progress";

const completeInput = {
  hasAccount: true,
  username: "frank",
  usernameAutoGenerated: false,
  image: "https://example.com/photo.jpg",
  acceptedConnectionCount: 1,
  outgoingConnectionRequestCount: 0,
  workspaceCount: 1,
};

describe("buildGetStartedProgress", () => {
  test("reports all five completed steps", () => {
    const progress = buildGetStartedProgress(completeInput);

    expect(progress.completedCount).toBe(5);
    expect(progress.remainingCount).toBe(0);
    expect(progress.percent).toBe(100);
    expect(progress.isComplete).toBe(true);
    expect(progress.nextStep).toBeNull();
  });

  test("counts any assigned username, including an auto-generated one", () => {
    const progress = buildGetStartedProgress({
      ...completeInput,
      usernameAutoGenerated: true,
    });

    expect(progress.steps.find((step) => step.id === "username")?.complete).toBe(true);
  });

  test("does not count a removed photo", () => {
    const progress = buildGetStartedProgress({
      ...completeInput,
      image: null,
    });

    expect(progress.steps.find((step) => step.id === "photo")?.complete).toBe(false);
  });

  test("counts a sent request without waiting for approval", () => {
    const withoutRequest = buildGetStartedProgress({
      ...completeInput,
      acceptedConnectionCount: 0,
    });
    const withRequest = buildGetStartedProgress({
      ...completeInput,
      acceptedConnectionCount: 0,
      outgoingConnectionRequestCount: 1,
    });

    expect(withoutRequest.steps.find((step) => step.id === "connection")?.complete).toBe(false);
    expect(withRequest.steps.find((step) => step.id === "connection")?.complete).toBe(true);
  });

  test("requires at least one workspace", () => {
    const withoutWorkspace = buildGetStartedProgress({
      ...completeInput,
      workspaceCount: 0,
    });
    const withSeveral = buildGetStartedProgress({
      ...completeInput,
      workspaceCount: 3,
    });

    expect(withoutWorkspace.steps.find((step) => step.id === "workspace")?.complete).toBe(false);
    expect(withSeveral.steps.find((step) => step.id === "workspace")?.complete).toBe(true);
  });
});

describe("getStartedHeadline", () => {
  test("changes as each setup step is completed", () => {
    expect(getStartedHeadline(5)).toBe("Let’s get you started");
    expect(getStartedHeadline(4)).toBe("You’re off to a great start!");
    expect(getStartedHeadline(3)).toBe("You’re off to a great start!");
    expect(getStartedHeadline(2)).toBe("You’re making great progress!");
    expect(getStartedHeadline(1)).toBe("You’re almost there!");
    expect(getStartedHeadline(0)).toBe("You’re all set!");
  });
});

describe("isGetStartedWindowExpired", () => {
  const now = new Date("2026-08-28T12:00:00.000Z");

  test("keeps Get Started visible before day 14", () => {
    expect(
      isGetStartedWindowExpired("2026-08-14T12:00:00.001Z", now),
    ).toBe(false);
  });

  test("expires Get Started at day 14", () => {
    expect(
      isGetStartedWindowExpired("2026-08-14T12:00:00.000Z", now),
    ).toBe(true);
  });

  test("does not expire when account creation time is unavailable", () => {
    expect(isGetStartedWindowExpired(null, now)).toBe(false);
  });
});
